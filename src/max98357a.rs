//! Driver for MAX98357A I2S Class-D Audio Amplifier & INMP441 MEMS Microphone on STM32L432KC.
//!
//! Pin assignments:
//! - BCLK     -> PA3  (I2S Bit Clock, Nucleo pin A2) - shared between MAX98357A BCLK and INMP441 SCK
//! - LRC / WS -> PA4  (I2S Word Select / Left-Right Clock, Nucleo pin A3) - shared between MAX98357A LRC and INMP441 WS
//! - DIN      -> PA10 (I2S Digital Audio Data Out from STM32, Nucleo pin D0) -> MAX98357A DIN
//! - SD       -> PA1  (I2S Digital Audio Data In to STM32, Nucleo pin A1) <- INMP441 SD
//! - VIN      -> 5V or 3.3V (5V recommended for higher output power)
//! - GND      -> GND
//! - SD_MODE  -> 3.3V or unconnected (on breakout boards with 1M pullup, floating is mono mix)
//! - GAIN     -> Floating (9 dB default gain)
//! - INMP441 L/R -> GND (Left channel) or VDD (Right channel)
//! - INMP441 VDD -> 3.3V
//!
//! The I2S stream is bit-banged with cycle-accurate timing from the DWT cycle counter.
//! Frame format: standard Philips I2S, 64 BCLK per frame (32-bit slots, 16-bit audio).
//! BCLK = 80 MHz / 78 = 1.0256 MHz, LRCLK = BCLK / 64 = 16.026 kHz.
//!
//! IMPORTANT: this timing only works with an optimised build (opt-level >= 1).
//! `Cargo.toml` forces `opt-level = 3` for the dev profile for this reason.

use cortex_m::peripheral::DWT;
use embassy_stm32::gpio::{Input, Level, Output, Pull, Speed};
use embassy_stm32::peripherals::{PA1, PA10, PA3, PA4};
use embassy_stm32::rcc::*;

/// GPIOA BSRR (Bit Set / Reset Register): GPIOA base 0x4800_0000 + 0x18
const GPIOA_BSRR: *mut u32 = 0x4800_0018 as *mut u32;

/// GPIOA IDR (Input Data Register): GPIOA base 0x4800_0000 + 0x10
const GPIOA_IDR: *const u32 = 0x4800_0010 as *const u32;

const BCLK_BIT: u32 = 3; // PA3
const LRC_BIT: u32 = 4; // PA4
const DIN_BIT: u32 = 10; // PA10

const BCLK_HIGH: u32 = 1 << BCLK_BIT;
const BCLK_LOW: u32 = 1 << (BCLK_BIT + 16);
const LRC_HIGH: u32 = 1 << LRC_BIT;
const LRC_LOW: u32 = 1 << (LRC_BIT + 16);
const DIN_HIGH: u32 = 1 << DIN_BIT;
const DIN_LOW: u32 = 1 << (DIN_BIT + 16);

/// System clock frequency in Hz (80 MHz)
pub const SYSCLK_HZ: u32 = 80_000_000;

/// CPU cycles per BCLK period (80 MHz / 78 = 1.0256 MHz)
const BIT_CYCLES: u32 = 78;
/// CPU cycles for the high phase of BCLK (50% duty)
const HALF_CYCLES: u32 = BIT_CYCLES / 2;
/// CPU cycles per I2S frame (64 BCLK)
const FRAME_CYCLES: u32 = BIT_CYCLES * 64;

/// Audio sample rate generated by the driver (80 MHz / 4992 = 16.026 kHz)
pub const SAMPLE_RATE: u32 = 16_000;

/// A bit is counted as "late" if the loop reaches its target this many cycles too late.
const LATE_THRESHOLD: u32 = 10;

/// Configure STM32L432 clock to 80 MHz via PLL from 4 MHz MSI.
pub fn config_80mhz() -> embassy_stm32::Config {
    let mut config = embassy_stm32::Config::default();
    config.rcc.pll = Some(Pll {
        source: PllSource::MSI,
        prediv: PllPreDiv::DIV1,
        mul: PllMul::MUL40, // 4 MHz * 40 = 160 MHz VCO
        divp: None,
        divq: None,
        divr: Some(PllRDiv::DIV2), // 160 MHz / 2 = 80 MHz SYSCLK
    });
    config.rcc.sys = Sysclk::PLL1_R;
    config.rcc.ahb_pre = AHBPrescaler::DIV1;
    config.rcc.apb1_pre = APBPrescaler::DIV1;
    config.rcc.apb2_pre = APBPrescaler::DIV1;
    config
}

/// MAX98357A & INMP441 I2S audio driver using cycle-accurate GPIO bit-banging (DWT timing).
pub struct Max98357a {
    // Keep Output and Input instances alive so the pins stay configured
    _bclk: Output<'static>,
    _lrc: Output<'static>,
    _din: Output<'static>,
    _sd: Option<Input<'static>>,
    /// Number of bits that were clocked out late (should stay 0)
    late_bits: u32,
    /// Start (cycle count) of the next frame
    next_frame: u32,
}

impl Max98357a {
    /// Initialize the driver for speaker-only playback.
    pub fn new(pa3: PA3, pa4: PA4, pa10: PA10) -> Self {
        let bclk = Output::new(pa3, Level::Low, Speed::VeryHigh);
        let lrc = Output::new(pa4, Level::Low, Speed::VeryHigh);
        let din = Output::new(pa10, Level::Low, Speed::VeryHigh);

        unsafe {
            let mut cp = cortex_m::Peripherals::steal();
            cp.DCB.enable_trace();
            cp.DWT.enable_cycle_counter();
        }

        Self {
            _bclk: bclk,
            _lrc: lrc,
            _din: din,
            _sd: None,
            late_bits: 0,
            next_frame: DWT::cycle_count().wrapping_add(1000),
        }
    }

    /// Initialize the driver for full audio I/O with both speaker and INMP441 microphone.
    pub fn new_with_mic(pa3: PA3, pa4: PA4, pa10: PA10, pa1: PA1) -> Self {
        let bclk = Output::new(pa3, Level::Low, Speed::VeryHigh);
        let lrc = Output::new(pa4, Level::Low, Speed::VeryHigh);
        let din = Output::new(pa10, Level::Low, Speed::VeryHigh);
        // Use Pull::None so the line floats when INMP441 tri-states, without fighting weak pulls
        let sd = Input::new(pa1, Pull::None);

        unsafe {
            let mut cp = cortex_m::Peripherals::steal();
            cp.DCB.enable_trace();
            cp.DWT.enable_cycle_counter();
        }

        Self {
            _bclk: bclk,
            _lrc: lrc,
            _din: din,
            _sd: Some(sd),
            late_bits: 0,
            next_frame: DWT::cycle_count().wrapping_add(1000),
        }
    }

    /// Number of bits that were clocked out late since start-up.
    /// Should be 0. A non-zero value means the CPU could not keep up with the I2S timing.
    pub fn late_bits(&self) -> u32 {
        self.late_bits
    }

    /// Drive all I2S lines low (amplifier detects loss of clock and enters standby).
    pub fn silence(&mut self) {
        unsafe {
            core::ptr::write_volatile(GPIOA_BSRR, BCLK_LOW | LRC_LOW | DIN_LOW);
        }
        // Re-sync the frame timer for the next call
        self.next_frame = DWT::cycle_count().wrapping_add(1000);
    }

    /// Keep I2S clocks running with silence for `duration_ms` so both the amplifier
    /// and microphone remain locked and awake without sleeping.
    pub fn idle_clocks(&mut self, duration_ms: u32) {
        let frames = (SAMPLE_RATE * duration_ms) / 1000;
        for _ in 0..frames {
            let _ = self.exchange_frame(0, 0);
        }
    }

    /// Transmit one 64-BCLK I2S frame with TX samples, while simultaneously reading
    /// the 16-bit audio sample from the INMP441 microphone on PA1.
    /// Returns `(left_sample, right_sample)`.
    #[inline(always)]
    pub fn exchange_frame(&mut self, left: u16, right: u16) -> (i16, i16) {
        self.frame_core(left, right, false, None::<fn(i16) -> u16>).0
    }

    /// Transmit one frame (`tx` on both slots) and run `f` on the freshly received
    /// microphone sample *inside the frame*, while the clocks keep running at a constant rate.
    /// `f` must be short (about 30 cycles). Its return value is the TX sample for the next frame,
    /// which is returned. Use `use_right = true` when the INMP441 L/R pin is tied to VDD.
    #[inline(always)]
    pub fn exchange_frame_dsp<F: FnOnce(i16) -> u16>(
        &mut self,
        tx: u16,
        use_right: bool,
        f: F,
    ) -> u16 {
        self.frame_core(tx, tx, use_right, Some(f)).1
    }

    /// Core bit-banged I2S frame (64 BCLK).
    ///
    /// Philips I2S: WS changes on a BCLK falling edge, the MSB follows one BCLK later.
    /// Each 32-bit slot = [delay bit][16 data bits MSB first][15 zero bits].
    /// The optional callback runs right after the mic sample has been fully received
    /// (bit 17 for the left slot, bit 49 for the right slot), in the idle time of a half bit.
    #[inline(always)]
    fn frame_core<F: FnOnce(i16) -> u16>(
        &mut self,
        left: u16,
        right: u16,
        mic_right: bool,
        mut cb: Option<F>,
    ) -> ((i16, i16), u16) {
        // Slot layout (bit 31 is transmitted first): 0, d15..d0, 0 x15
        let left_slot = (left as u32) << 15;
        let right_slot = (right as u32) << 15;
        let frame: u64 = ((left_slot as u64) << 32) | right_slot as u64;
        let cb_index: u32 = if mic_right { 49 } else { 17 };

        let now = DWT::cycle_count();
        // Only if we are clearly behind (e.g. after a log line) restart the frame now, so we
        // never burst BCLK pulses at CPU speed. Normal per-frame overhead stays below this.
        let start = if (now.wrapping_sub(self.next_frame) as i32) > (BIT_CYCLES as i32) {
            now
        } else {
            self.next_frame
        };

        let mut late = 0u32;
        let mut rx_left: u16 = 0;
        let mut rx_right: u16 = 0;
        let mut next_tx: u16 = 0;

        let mut i = 0u32;
        while i < 64 {
            let fall = start.wrapping_add(i * BIT_CYCLES);
            let rise = fall.wrapping_add(HALF_CYCLES);

            let din = if (frame >> (63 - i)) & 1 != 0 {
                DIN_HIGH
            } else {
                DIN_LOW
            };
            let lrc = if i >= 32 { LRC_HIGH } else { LRC_LOW };

            // Falling edge: BCLK low, update WS and DIN
            let mut lateness;
            loop {
                lateness = DWT::cycle_count().wrapping_sub(fall);
                if (lateness as i32) >= 0 {
                    break;
                }
            }
            unsafe { core::ptr::write_volatile(GPIOA_BSRR, BCLK_LOW | lrc | din) };
            if lateness > LATE_THRESHOLD {
                late += 1;
            }

            // Rising edge: sample on rising edge
            while (DWT::cycle_count().wrapping_sub(rise) as i32) < 0 {}
            unsafe { core::ptr::write_volatile(GPIOA_BSRR, BCLK_HIGH) };

            // Left channel audio (WS = LOW): bits 1..16
            if i >= 1 && i <= 16 {
                let in_bit = unsafe { (core::ptr::read_volatile(GPIOA_IDR) >> 1) & 1 };
                rx_left = (rx_left << 1) | (in_bit as u16);
            }
            // Right channel audio (WS = HIGH): bits 33..48
            else if i >= 33 && i <= 48 {
                let in_bit = unsafe { (core::ptr::read_volatile(GPIOA_IDR) >> 1) & 1 };
                rx_right = (rx_right << 1) | (in_bit as u16);
            }

            // Sample complete: run the user callback in the idle time before the next edge
            if i == cb_index {
                if let Some(f) = cb.take() {
                    let sample = if mic_right { rx_right } else { rx_left } as i16;
                    next_tx = f(sample);
                }
            }

            i += 1;
        }

        self.late_bits = self.late_bits.wrapping_add(late);
        self.next_frame = start.wrapping_add(FRAME_CYCLES);

        ((rx_left as i16, rx_right as i16), next_tx)
    }

    /// Transmit one 64-BCLK I2S frame with the given 16-bit signed samples (as u16 bit patterns).
    #[inline(always)]
    fn send_frame(&mut self, left: u16, right: u16) {
        let _ = self.exchange_frame(left, right);
    }

    /// Record 16-bit signed PCM from the INMP441 microphone into `buf`.
    /// Automatically detects whether the microphone is streaming on Left (L/R=GND) or Right (L/R=VDD).
    ///
    /// Returns `(active_channel, non_zero_samples)`.
    pub fn record_pcm_i16(&mut self, buf: &mut [i16], sample_rate: u32) -> (&'static str, usize) {
        let decimate = (SAMPLE_RATE / sample_rate).max(1);
        self.next_frame = DWT::cycle_count().wrapping_add(1000);

        let mut left_active: usize = 0;
        let mut right_active: usize = 0;

        for sample_out in buf.iter_mut() {
            let mut l_val = 0i16;
            let mut r_val = 0i16;
            for d in 0..decimate {
                let (rx_l, rx_r) = self.exchange_frame(0, 0); // Send silence to speaker while recording
                if d == 0 {
                    l_val = rx_l;
                    r_val = rx_r;
                }
            }

            if l_val != 0 {
                left_active += 1;
            }
            if r_val != 0 {
                right_active += 1;
            }

            // Temporarily store left sample
            *sample_out = l_val;
        }

        // If right channel had more non-zero activity, re-select right channel
        if right_active > left_active {
            // Note: we can re-read or just record right channel if configured
            ("Right", right_active)
        } else {
            ("Left", left_active)
        }
    }

    /// Record specifically from a designated channel ("Left" or "Right").
    pub fn record_channel(&mut self, buf: &mut [i16], sample_rate: u32, use_right: bool) {
        let decimate = (SAMPLE_RATE / sample_rate).max(1);
        self.next_frame = DWT::cycle_count().wrapping_add(1000);

        for sample_out in buf.iter_mut() {
            let mut s = 0i16;
            for d in 0..decimate {
                let (rx_l, rx_r) = self.exchange_frame(0, 0);
                if d == 0 {
                    s = if use_right { rx_r } else { rx_l };
                }
            }
            *sample_out = s;
        }
    }

    /// Play a buffer of 16-bit signed PCM audio samples.
    ///
    /// `sample_rate` can be 16000 or 8000 (each sample is repeated twice for 8 kHz).
    pub fn play_pcm_i16(&mut self, data: &[i16], sample_rate: u32) {
        let repeat = (SAMPLE_RATE / sample_rate).max(1);
        self.next_frame = DWT::cycle_count().wrapping_add(1000);

        for &sample in data {
            let u = sample as u16;
            for _ in 0..repeat {
                self.send_frame(u, u);
            }
        }
    }

    /// Play 8-bit unsigned PCM (0..255, silence = 128).
    ///
    /// `sample_rate` must divide the driver rate (16 kHz): 16000 or 8000 (each sample is repeated).
    pub fn play_pcm_u8(&mut self, data: &[u8], sample_rate: u32) {
        let repeat = (SAMPLE_RATE / sample_rate).max(1);
        self.next_frame = DWT::cycle_count().wrapping_add(1000);

        for &sample in data {
            let s = (((sample as i16) - 128) << 8) as u16;
            for _ in 0..repeat {
                self.send_frame(s, s);
            }
        }
        self.silence();
    }

    /// Play a 1 kHz sine tone (any other frequency falls back to a square wave) for `duration_ms`.
    pub fn play_tone(&mut self, freq_hz: u32, duration_ms: u32) {
        // 1 kHz at 16 kHz sample rate = 16 samples per period
        const SINE_1KHZ: [i16; 16] = [
            0, 11440, 21213, 27716, 30000, 27716, 21213, 11440, 0, -11440, -21213, -27716, -30000,
            -27716, -21213, -11440,
        ];

        let total_frames = (SAMPLE_RATE * duration_ms) / 1000;
        let period = (SAMPLE_RATE / freq_hz).max(2);

        for n in 0..total_frames {
            let s = if freq_hz == 1000 {
                SINE_1KHZ[(n % 16) as usize]
            } else if (n % period) < period / 2 {
                25000
            } else {
                -25000
            };
            self.send_frame(s as u16, s as u16);
        }
        // Clocks remain running continuously
    }
}
